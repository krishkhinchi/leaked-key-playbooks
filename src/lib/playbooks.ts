export function getPlaybook(providerSlug: string, credentialSlug: string): Playbook | undefined {
  return PLAYBOOKS.find(p => p.providerSlug === providerSlug && p.credentialSlug === credentialSlug);
}

export function getPlaybooksByProvider(providerSlug: string): Playbook[] {
  return PLAYBOOKS.filter(p => p.providerSlug === providerSlug);
}

export function searchPlaybooks(query: string): Playbook[] {
  const q = query.toLowerCase();
  return PLAYBOOKS.filter(p =>
    p.provider.toLowerCase().includes(q) ||
    p.credentialName.toLowerCase().includes(q) ||
    p.description.toLowerCase().includes(q) ||
    p.providerCategory.toLowerCase().includes(q) ||
    p.providerSlug.toLowerCase().includes(q) ||
    p.credentialSlug.toLowerCase().includes(q)
  );
}
